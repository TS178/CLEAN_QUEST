/*
 * ゲームの数値設定（ここを書きかえるだけで調整できる）
 * ------------------------------------------------------------
 * - event.id を変えると「別のイベント」になり、そうじミッション・クイズの報酬を
 *   もう一度もらえる（受け取り済みの記録は「イベントID:ミッションID」で管理）。
 * - 受け取った報酬は、受け取ったときの数値で保存される。あとから数値を変えても、
 *   すでに受け取った分は変わらない。
 *
 * 【遊び方の流れ】
 *   1. 時間がたつと ホームの ビーチが よごれる（よごれ度 1〜3）
 *   2. ゴミを 分別ゴミばこへ ドラッグ・スワイプして すてる → クリーンポイント
 *   3. ポイントで エサ（アクアドロップ）や すみかの アイテムを かう
 *   4. エサを あげて けいけんち → ようせいが 進化（こども → 進化1 → 最終進化）
 *   クイズ・実際のゴミの記録は ボーナスの ポイント（けいけんちは エサだけ）。
 *
 * 【配分の切りかえ】 pace を "event"（イベント当日）か "long"（長く遊ぶ）に する。
 */
(function () {
  const BCT = (window.BCT = window.BCT || {});

  const PACES = {
    // イベント当日：2〜3時間で 最終進化に とどく。ビーチは 15分ごとに よごれる
    event: {
      name: "イベント",
      levels: [0, 60, 150, 280, 450],
      dirtEveryMin: 15,
    },
    // 長く遊ぶ：1週間ほどで 最終進化。ビーチは 3時間ごとに よごれる
    long: {
      name: "ながく あそぶ",
      levels: [0, 150, 400, 800, 1400],
      dirtEveryMin: 180,
    },
  };
  const pace = "event";

  BCT.CONFIG = {
    schema: 2,
    event: {
      id: "beachclean-2026",
      name: "ビーチクリーン探検隊",
      // 【ちず・ばしょの きろくを つかえる 日】（js/event-mode.js）
      // ふだん 家で つかう ときに 家の 位置を きろく しない よう、イベントの 日だけ ひらく。
      // イベントの 日付が きまったら ここに かく（例：["2026-11-08"]。2日なら ["2026-11-08", "2026-11-09"]）。
      // その日は 0時〜24時、だれでも 自動で ひらく。空の あいだは 日付では ひらかない。
      days: [],
      // 受付の QR コード（運営画面 operator.html の「受付用 QR」）で ひらいた 人は、その日の おわりまで ひらく。
      // QR の 中身は「アプリの URL?event=この あいことば」。公開して いる コードからも 見えるので、鍵ではなく
      // 「うっかり 家の 位置を きろく しない」ための しくみ。かえる ときは 受付の QR も つくりなおす。
      openKey: "pikapika-umi-2026",
    },
    pace,
    PACES,
    // レベルに必要な 累計けいけんち（左から Lv1, Lv2, …）
    levels: PACES[pace].levels,
    // レベルごとの 見た目の段階（1=こども 2=進化1 3=最終進化）。進化は 全2段階
    stageOfLevel: [1, 1, 2, 2, 3],
    // ミッションの ごほうび（けいけんちは 0。けいけんちは エサだけ）
    reward: {
      quiz: { xp: 0, coins: 20 },  // クイズ1もんを はじめて クリア
      clean: { xp: 0, coins: 20 }, // ゴミの しゅるいを はじめて きろく（しゅるいごとに1かい）
    },
    // ホームの ビーチの よごれ と 分別
    beach: {
      dirtEveryMin: PACES[pace].dirtEveryMin, // この分ごとに よごれが 1だん すすむ
      itemsPerLevel: 3,                       // 1だんで ふえる ゴミの数
      maxLevel: 3,                            // よごれ度は 3まで（それ以上 ふえない）
      startLevel: 1,                          // はじめて あそぶ ときの よごれ度
      pointsPerItem: 5,                       // 1こ 正しく すてると もらえる クリーンポイント
      pointsPerTreasure: 5,                   // きれいな砂浜の貝殻・シーグラスを1つ拾う報酬
    },
    // エサ（アクアドロップ）：たかいほど おとく
    foods: [
      { id: "drop_blue", name: "アクアドロップ", color: "#4aa8e0", price: 10, xp: 10, note: "まいにち あげる ドロップ" },
      { id: "drop_green", name: "シャイニードロップ", color: "#3cbf7a", price: 40, xp: 50, note: "ちょっと とくべつ" },
      { id: "drop_rainbow", name: "レインボードロップ", color: "rainbow", price: 140, xp: 200, note: "しんかの まえに" },
    ],
    affection: {
      perStage: 5, // なでる 5かいで なつきど が1だん あがる
      maxStage: 3,
    },
    toyUnlockPlays: 3, // おなじ おもちゃで 3かい あそぶと ポーズを おぼえる
    eventFrameQuiz: 10, // イベントきねんフレーム：クイズ この数 ＋ そうじミッション1つ以上
    photo: { width: 1080, height: 1440 }, // 記念写真の大きさ（たて長 3:4）
  };
  BCT.foodOf = (id) => BCT.CONFIG.foods.find((f) => f.id === id) || null;
})();
