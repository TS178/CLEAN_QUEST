// Package only the two missing categories; approved collection files stay untouched.
import fs from 'node:fs';
import {launch} from '../tests/e2e/cdp.mjs';
const b=await launch({port:12051,mobile:false});
try {
  await b.goto('http://127.0.0.1:8766/preview-collection-art.html');
  const sprites={};
  fs.mkdirSync('assets/mission-icons',{recursive:true});
  for(const key of ['float','other']) {
    const source=`assets/art-source/mission-icons/${key}.png`;
    const data=await b.ev(`(async()=>{
      const im=new Image();im.src=${JSON.stringify(source)};await im.decode();
      const c=document.createElement('canvas');c.width=im.width;c.height=im.height;
      const g=c.getContext('2d');g.drawImage(im,0,0);const d=g.getImageData(0,0,c.width,c.height).data;
      let l=c.width,t=c.height,r=0,b=0;
      for(let y=0;y<c.height;y++)for(let x=0;x<c.width;x++)if(d[(y*c.width+x)*4+3]>32){l=Math.min(l,x);t=Math.min(t,y);r=Math.max(r,x);b=Math.max(b,y);}
      l=Math.max(0,l-4);t=Math.max(0,t-4);r=Math.min(c.width-1,r+4);b=Math.min(c.height-1,b+4);
      const w=r-l+1,h=b-t+1,scale=Math.min(1,420/Math.max(w,h));
      const out=document.createElement('canvas');out.width=Math.round(w*scale);out.height=Math.round(h*scale);
      out.getContext('2d').drawImage(c,l,t,w,h,0,0,out.width,out.height);
      return {width:out.width,height:out.height,src:out.toDataURL('image/webp',.94)};
    })()`);
    const file=`assets/mission-icons/${key}.webp`;
    fs.writeFileSync(file,Buffer.from(data.src.split(',')[1],'base64'));
    sprites[`mission_${key}`]={...data,file,source};
  }
  fs.writeFileSync('js/mission-sprites.js','/* Generated by tools/pack-mission-art.mjs */\nwindow.BCT=window.BCT||{};\nwindow.BCT.MISSION_SPRITES='+JSON.stringify(sprites)+';\n');
  fs.writeFileSync('assets/art-source/mission-icons/manifest.json',JSON.stringify(Object.fromEntries(Object.entries(sprites).map(([id,{src,...s}])=>[id,s])),null,2));
  console.log('Packaged two mission icons; existing collection assets unchanged.');
}finally{b.close();}
